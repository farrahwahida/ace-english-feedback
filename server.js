const http = require('http');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

// Lightweight .env loader (no external dependency)
(function loadEnv() {
  const envPath = path.join(__dirname, '.env');
  if (!fs.existsSync(envPath)) return;
  const lines = fs.readFileSync(envPath, 'utf8').split(/\r?\n/);
  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) continue;
    const eqIdx = trimmed.indexOf('=');
    if (eqIdx === -1) continue;
    const key = trimmed.slice(0, eqIdx).trim();
    let val = trimmed.slice(eqIdx + 1).trim();
    if (
      (val.startsWith('"') && val.endsWith('"')) ||
      (val.startsWith("'") && val.endsWith("'"))
    ) {
      val = val.slice(1, -1);
    }
    if (process.env[key] === undefined) {
      process.env[key] = val;
    }
  }
})();

const { TP_RUBRIC } = require('./src/tp-rubric');
const { buildCsvExportUrl, mapSheetRows } = require('./src/csv-parser');
const { generateReport } = require('./src/report-generator');
const {
  getConfig,
  getPublicConfig,
  saveConfig,
  getReportsMap,
  getReport,
  saveReport,
  deleteReport,
} = require('./src/store');

const PUBLIC_DIR = path.join(__dirname, 'public');

const MIME_TYPES = {
  '.html': 'text/html; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.js': 'application/javascript; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
};

function sendJson(res, statusCode, payload) {
  const body = JSON.stringify(payload);
  res.writeHead(statusCode, {
    'Content-Type': 'application/json; charset=utf-8',
    'Cache-Control': 'no-store',
  });
  res.end(body);
}

function readBody(req) {
  return new Promise((resolve, reject) => {
    const chunks = [];
    let size = 0;
    req.on('data', (chunk) => {
      size += chunk.length;
      if (size > 2 * 1024 * 1024) {
        reject(new Error('Request body too large'));
        req.destroy();
        return;
      }
      chunks.push(chunk);
    });
    req.on('end', () => {
      const raw = Buffer.concat(chunks).toString('utf8');
      if (!raw) return resolve({});
      try {
        resolve(JSON.parse(raw));
      } catch {
        reject(new Error('Invalid JSON body'));
      }
    });
    req.on('error', reject);
  });
}

async function fetchSheetEntries(sheetUrl) {
  const csvUrl = buildCsvExportUrl(sheetUrl);
  const response = await fetch(csvUrl, {
    headers: { 'User-Agent': 'AceEnglishFeedbackBot/1.0' },
  });
  if (!response.ok) {
    throw new Error(
      `Could not fetch Google Sheet (HTTP ${response.status}). Ensure link sharing is set to "Anyone with the link can view".`
    );
  }
  const csvText = await response.text();
  if (csvText.trim().startsWith('<!DOCTYPE html') || csvText.trim().startsWith('<html')) {
    throw new Error(
      'Google Sheet returned an HTML login page instead of CSV. Make sure the sheet is shared as "Anyone with the link can view".'
    );
  }
  return mapSheetRows(csvText);
}

function mergeWithSavedReports(entries, reportsMap) {
  return entries.map((entry) => {
    const saved = reportsMap[entry.id];
    return {
      ...entry,
      report: saved
        ? {
            text: saved.text,
            engine: saved.engine,
            status: saved.status || 'ready',
            language: saved.language || entry.reportLanguage,
            fallbackReason: saved.fallbackReason || null,
            updatedAt: saved.updatedAt,
          }
        : null,
    };
  });
}

async function handleApi(req, res, urlObj) {
  const pathname = urlObj.pathname;

  if (req.method === 'GET' && pathname === '/api/health') {
    return sendJson(res, 200, { ok: true, time: new Date().toISOString() });
  }

  if (req.method === 'GET' && pathname === '/api/rubric') {
    return sendJson(res, 200, { rubric: TP_RUBRIC });
  }

  if (req.method === 'GET' && pathname === '/api/config') {
    return sendJson(res, 200, { config: getPublicConfig() });
  }

  if (req.method === 'POST' && pathname === '/api/config') {
    const body = await readBody(req);
    const updated = saveConfig(body);
    return sendJson(res, 200, { config: updated });
  }

  if (req.method === 'GET' && pathname === '/api/sheet') {
    const cfg = getConfig();
    const sheetUrl = urlObj.searchParams.get('sheetUrl') || cfg.sheetUrl;
    const entries = await fetchSheetEntries(sheetUrl);
    const reportsMap = getReportsMap();

    let autoGeneratedCount = 0;
    if (cfg.autoGenerateOnSync) {
      for (const entry of entries) {
        if (!reportsMap[entry.id]) {
          const result = await generateReport(entry, cfg, { mode: 'auto' });
          reportsMap[entry.id] = saveReport(entry.id, {
            entry,
            text: result.text,
            engine: result.engine,
            language: result.language,
            fallbackReason: result.fallbackReason || null,
            status: 'ready',
          });
          autoGeneratedCount++;
        }
      }
    }

    const merged = mergeWithSavedReports(entries, reportsMap);
    return sendJson(res, 200, {
      entries: merged,
      syncedAt: new Date().toISOString(),
      autoGeneratedCount,
    });
  }

  if (req.method === 'GET' && pathname === '/api/reports') {
    const reportsMap = getReportsMap();
    const customEntries = Object.values(reportsMap)
      .filter((r) => r.entry && r.entry.source === 'manual')
      .sort((a, b) => String(b.updatedAt || '').localeCompare(String(a.updatedAt || '')))
      .map((r) => ({
        ...r.entry,
        id: r.id,
        report: {
          text: r.text,
          engine: r.engine,
          status: r.status || 'ready',
          language: r.language || r.entry.reportLanguage,
          fallbackReason: r.fallbackReason || null,
          updatedAt: r.updatedAt,
        },
      }));
    return sendJson(res, 200, { entries: customEntries });
  }

  if (req.method === 'POST' && pathname === '/api/generate') {
    const body = await readBody(req);
    const cfg = getConfig();
    const rawEntry = body.entry || {};
    const mode = body.mode || 'auto';

    const entryId =
      rawEntry.id ||
      'manual_' + crypto.randomBytes(6).toString('hex');

    const entry = {
      id: entryId,
      source: rawEntry.source || 'manual',
      timestamp: rawEntry.timestamp || new Date().toLocaleString('en-US'),
      studentName: rawEntry.studentName || '',
      yearForm: rawEntry.yearForm || '',
      topic: rawEntry.topic || '',
      skillFocus: rawEntry.skillFocus || '',
      strengthsGaps: rawEntry.strengthsGaps || '',
      homework: rawEntry.homework || '',
      reportLanguage: body.languageOverride || rawEntry.reportLanguage || 'Bilingual',
      tp: rawEntry.tp || 'TP3',
    };

    const result = await generateReport(entry, cfg, { mode });
    const saved = saveReport(entryId, {
      entry,
      text: result.text,
      engine: result.engine,
      language: result.language,
      fallbackReason: result.fallbackReason || null,
      status: 'ready',
    });

    return sendJson(res, 200, {
      entry: {
        ...entry,
        report: {
          text: saved.text,
          engine: saved.engine,
          status: saved.status,
          language: saved.language,
          fallbackReason: saved.fallbackReason,
          updatedAt: saved.updatedAt,
        },
      },
    });
  }

  if (req.method === 'POST' && pathname === '/api/generate-pending') {
    const body = await readBody(req);
    const cfg = getConfig();
    const mode = body.mode || 'auto';
    const entries = Array.isArray(body.entries) ? body.entries : [];
    const reportsMap = getReportsMap();
    const generated = [];

    for (const entry of entries) {
      if (!entry || !entry.id || reportsMap[entry.id]) continue;
      const result = await generateReport(entry, cfg, { mode });
      const saved = saveReport(entry.id, {
        entry,
        text: result.text,
        engine: result.engine,
        language: result.language,
        fallbackReason: result.fallbackReason || null,
        status: 'ready',
      });
      generated.push({
        ...entry,
        report: {
          text: saved.text,
          engine: saved.engine,
          status: saved.status,
          language: saved.language,
          fallbackReason: saved.fallbackReason,
          updatedAt: saved.updatedAt,
        },
      });
    }

    return sendJson(res, 200, { count: generated.length, generated });
  }

  if (pathname.startsWith('/api/reports/')) {
    const id = decodeURIComponent(pathname.slice('/api/reports/'.length));
    if (!id) {
      return sendJson(res, 400, { error: 'Missing report id' });
    }

    if (req.method === 'POST') {
      const body = await readBody(req);
      const existing = getReport(id) || {};
      const patch = {};
      if (body.text !== undefined) patch.text = String(body.text);
      if (body.status !== undefined) patch.status = String(body.status);
      if (body.entry !== undefined) patch.entry = body.entry;
      if (!existing.engine && body.text !== undefined) patch.engine = 'edited';

      const saved = saveReport(id, patch);
      return sendJson(res, 200, { report: saved });
    }

    if (req.method === 'DELETE') {
      const deleted = deleteReport(id);
      return sendJson(res, 200, { deleted });
    }
  }

  return sendJson(res, 404, { error: 'API route not found' });
}

function serveStatic(req, res, pathname) {
  let reqPath = pathname === '/' ? '/index.html' : pathname;
  reqPath = decodeURIComponent(reqPath);
  const fullPath = path.normalize(path.join(PUBLIC_DIR, reqPath));

  if (!fullPath.startsWith(PUBLIC_DIR)) {
    res.writeHead(403);
    return res.end('Forbidden');
  }

  fs.readFile(fullPath, (err, content) => {
    if (err) {
      if (err.code === 'ENOENT') {
        res.writeHead(404);
        return res.end('Not found');
      }
      res.writeHead(500);
      return res.end('Server error');
    }

    const ext = path.extname(fullPath).toLowerCase();
    res.writeHead(200, {
      'Content-Type': MIME_TYPES[ext] || 'application/octet-stream',
      'Cache-Control': 'no-store',
    });
    res.end(content);
  });
}

function createServer() {
  return http.createServer(async (req, res) => {
    try {
      const urlObj = new URL(req.url, `http://${req.headers.host || 'localhost'}`);
      if (urlObj.pathname.startsWith('/api/')) {
        await handleApi(req, res, urlObj);
      } else {
        serveStatic(req, res, urlObj.pathname);
      }
    } catch (err) {
      console.error('[Server Error]', err);
      if (!res.headersSent) {
        sendJson(res, 500, { error: err.message || 'Internal server error' });
      }
    }
  });
}

if (require.main === module) {
  const PORT = Number(process.env.PORT) || 3456;
  const server = createServer();
  server.listen(PORT, () => {
    console.log(`Ace English Parent Feedback Studio running at http://localhost:${PORT}`);
  });
}

module.exports = { createServer };
